"""Render the same-universe budget results as Markdown tables.

Consumes ``runs/v3_graph_budget/summary.json`` produced by
``scripts.run_budget_experiment`` and writes
``runs/v3_graph_budget/budget_tables.md``.  It only formats existing results;
it never re-runs or re-orders a search.

Usage::

    python -m scripts.summarize_budget
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

KIT = Path(__file__).resolve().parents[1]
RUN = KIT / "runs" / "v3_graph_budget"
OUT = RUN / "budget_tables.md"


def _fmt(value, digits=1):
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def overall_table(summary: Dict[str, Any]) -> List[str]:
    lines = [
        "| panel | mode | budget | inputs | confirmed MSMS | confirmed MMBS | "
        "undecided MSMS/MMBS | UNKNOWN MSMS/MMBS | complete inputs "
        "| first MSMS probes (mean) | first MMBS probes (mean) | probes | wall s |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for panel in ("U_graph", "U_c"):
        for mode in ("exhaustive", "graph"):
            for row in summary.get("totals", {}).get(panel, {}).get(mode, []):
                # Per-budget first-confirmation means live in the per-task
                # budget summaries; rebuild them from the stored totals only
                # when the summarizer has them.
                lines.append(
                    f"| {panel} | {mode} | {int(row['fraction']*100)}% "
                    f"| {row['inputs']} "
                    f"| {row['confirmed_msms']} | {row['confirmed_mmbs']} "
                    f"| {row['undecided_msms']}/{row['undecided_mmbs']} "
                    f"| {row['unknown_msms']}/{row['unknown_mmbs']} "
                    f"| {row['complete_inputs']}/{row['inputs']} "
                    f"| {_fmt(row.get('first_msms_probes_mean'))} "
                    f"| {_fmt(row.get('first_mmbs_probes_mean'))} "
                    f"| {row['probes']} "
                    f"| {_fmt(row['wall_seconds'])} |")
    return lines


def limits_table(summary: Dict[str, Any]) -> List[str]:
    lines = [
        "| task | panel | |U| | full subsets | 10% | 25% | 50% | 75% | 100% |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for task_id, panels in summary.get("tasks", {}).items():
        for panel, block in panels.items():
            rows = block["modes"]["exhaustive"]["budget_summary"]
            if not rows:
                continue
            limits = [row["limit_min"] for row in rows]
            full = 2 ** len(block["universe"])
            lines.append(
                f"| {task_id} | {panel} | {len(block['universe'])} | {full} "
                f"| {limits[0]} | {limits[1]} | {limits[2]} "
                f"| {limits[3]} | {limits[4]} |")
    return lines


def curves(summary: Dict[str, Any]) -> List[str]:
    lines = ["### Confirmed relations by task (sum over searched inputs)", ""]
    lines += [
        "| task | panel | mode | 10% | 25% | 50% | 75% | 100% |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for task_id, panels in summary.get("tasks", {}).items():
        for panel, block in panels.items():
            for mode in ("exhaustive", "graph"):
                rows = block["modes"][mode]["budget_summary"]
                if not rows:
                    continue
                cells = [f"{row['confirmed_msms']}/{row['confirmed_mmbs']}"
                         for row in rows]
                lines.append(f"| {task_id} | {panel} | {mode} | "
                             + " | ".join(cells) + " |")
    return lines


def first_costs(summary: Dict[str, Any]) -> List[str]:
    lines = [
        "### First confirmed MSMS/MMBS: probes from the start of the input",
        "",
        "| task | panel | mode | first MSMS probes (mean) | first MMBS probes (mean) |",
        "|---|---|---|---:|---:|",
    ]
    for task_id, panels in summary.get("tasks", {}).items():
        for panel, block in panels.items():
            for mode in ("exhaustive", "graph"):
                rows = block["modes"][mode]["budget_summary"]
                if not rows:
                    continue
                full = rows[-1]
                lines.append(
                    f"| {task_id} | {panel} | {mode} "
                    f"| {_fmt(full.get('first_msms_probes_mean'))} "
                    f"| {_fmt(full.get('first_mmbs_probes_mean'))} |")
    return lines


def main() -> int:
    summary = json.loads((RUN / "summary.json").read_text(encoding="utf-8"))
    text = "\n".join([
        "# Same-universe budget tables", "",
        "Generated by `python -m scripts.summarize_budget` from "
        "`runs/v3_graph_budget/summary.json`.", "",
        "## Budget limits (ceil, clipped to the full enumeration)", "",
        *limits_table(summary), "",
        "## Totals by budget", "",
        *overall_table(summary), "",
        "## Discovery curves (MSMS/MMBS)", "",
        *curves(summary), "",
        *first_costs(summary), "",
    ])
    OUT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
